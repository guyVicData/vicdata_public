// VicData 0.8 SMT r4 (stage I): the (i) audit, view by view -- what each view's source (i) said before
// this round, what it says now (its method, src/catalogue/methods*.ts, filled as a host with no data of
// its own would fill it), and what the code did that the old (i) didn't say. Reads the three audits made
// from the code (docs/v0.8/smt_r4_method_audit/{teacher,admissions,smt}.json) and writes
// docs/v0.8/smt_r4_method_audit_v1.md.
//
//   npx -y tsx scripts/method-audit.ts
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { DATAVIEWS } from "../src/catalogue/dataviews";
import { methodOf } from "../src/catalogue/methods";

type Audit = { id: string; label: string; currentInfo: string; notInInfoNow: string[] };
const ROOT = path.resolve(__dirname, "..");
const dir = path.join(ROOT, "docs/v0.8/smt_r4_method_audit");
const audits = new Map<string, Audit>();
for (const f of ["teacher", "admissions", "smt"]) for (const a of JSON.parse(readFileSync(path.join(dir, `${f}.json`), "utf8")) as Audit[]) audits.set(a.id, a);

const product = (id: string) => (id.startsWith("DV-ADM") ? "Admissions" : id.startsWith("DV-SMT") ? "SMT" : "Teacher");
const out: string[] = [
  "# 0.8 SMT r4: the (i) audit, view by view",
  "",
  "Generated by `scripts/method-audit.ts` from the code audits in `docs/v0.8/smt_r4_method_audit/` and the methods in `src/catalogue/methods*.ts`. **Every view's (i) changed**: each now ends with its method (sources, area, years, what is left out, the numbered steps under \"How it is calculated\", rounding). For each view: what the (i) said before, what it says now, and what the code did that the old (i) didn't say (now in the method).",
  "",
  "Placeholders in \"before\" are the parts the page fills in. In \"after\", a {placeholder} the host fills from the data shows its fallback words (\"the latest year held\", \"the comparison set\") or, for the census, the year from `years.ts`. The forward view (DV-SMT-C-PROJECTION) draws a method generated from the projection's settings; its stored fallback is shown here.",
  "",
];
for (const p of ["Teacher", "Admissions", "SMT"]) {
  const views = DATAVIEWS.filter((d) => product(d.id) === p);
  out.push(`## ${p} (${views.length} views)`, "");
  for (const d of views) {
    const a = audits.get(d.id);
    const m = methodOf(d.id, {})!;
    out.push(`### ${d.id}: ${d.label}`, "");
    out.push(`**Before.** ${a?.currentInfo ?? "(not in the audit)"}`, "");
    out.push("**After** (added to the (i)):", "");
    out.push(`- Sources: ${m.sources.join("; ")}.`, `- Area: ${m.geography}`, `- Years: ${m.years}`);
    if (m.leftOut.length) out.push(`- Left out: ${m.leftOut.join(" ")}`);
    out.push("- How it is calculated:");
    m.steps.forEach((s, i) => out.push(`  ${i + 1}. ${s}`));
    if (m.rounding.length) out.push(`- Rounding: ${m.rounding.join(" ")}`);
    if (a?.notInInfoNow.length) {
      out.push("", "**The code did this; the old (i) didn't say it:**", "");
      for (const x of a.notInInfoNow) out.push(`- ${x}`);
    }
    out.push("");
  }
}
writeFileSync(path.join(ROOT, "docs/v0.8/smt_r4_method_audit_v1.md"), out.join("\n") + "\n");
console.log(`wrote docs/v0.8/smt_r4_method_audit_v1.md: ${DATAVIEWS.length} views`);
